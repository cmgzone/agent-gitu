/** Native Chromium verification against tests/helpers/subagent-orbs-preview.ts. */
const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const checks = [];
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 1024, height: 800, webPreferences: { contextIsolation: true, nodeIntegration: false, backgroundThrottling: false } });
  const errors = [];
  win.webContents.on('console-message', (_event, level, message) => { if (level >= 3) errors.push(message); });
  const evaluate = expression => win.webContents.executeJavaScript(expression);
  const key = value => { win.webContents.sendInputEvent({ type: 'keyDown', keyCode: value }); win.webContents.sendInputEvent({ type: 'keyUp', keyCode: value }); };
  await win.loadURL(process.argv[2]);
  await pause(200);
  assert.equal(await evaluate('document.querySelectorAll(".subagent-orb").length'), 9);
  assert.deepEqual(await evaluate('Array.from(document.querySelectorAll(".subagent-orb"), b => b.dataset.phase)'),
    ['working', 'reasoning', 'tool', 'waiting', 'blocked', 'complete', 'failed', 'idle', 'complete']);
  assert.deepEqual(await evaluate('Array.from(document.querySelectorAll(".subagent-face"), img => img.complete && img.naturalWidth > 0)'), Array(9).fill(true));
  assert.equal(await evaluate('getComputedStyle(document.querySelector(".subagent-presence")).backgroundColor'), 'rgba(0, 0, 0, 0)');
  assert.equal(await evaluate('getComputedStyle(document.querySelector(".subagent-presence")).borderTopWidth'), '0px');
  assert.equal(await evaluate('getComputedStyle(document.querySelector(".subagent-face")).animationName'), 'none');
  checks.push('Unboxed presence; nine loaded stationary avatars; all states');
  await evaluate('window.firstOrb = document.querySelector(".subagent-orb"); window.firstRing = firstOrb.querySelector(".subagent-ring"); firstOrb.focus();');
  assert.equal(await evaluate('document.querySelector(".subagent-peek").hidden'), false);
  assert.ok(await evaluate('document.querySelector(".subagent-peek").textContent.includes("Research Kenyan POS competitors")'));
  assert.ok(await evaluate('document.querySelector(".subagent-peek").textContent.includes("≈18.4k tokens")'));
  key('Enter'); await pause(30); key('Enter'); await pause(30);
  assert.equal(await evaluate('document.querySelector(".subagent-dialog").open'), true);
  checks.push('Keyboard focus reveals truthful details; Enter opens context');
  await evaluate('document.querySelector("#update").click()');
  assert.equal(await evaluate('document.querySelector(".subagent-orb") === window.firstOrb && firstOrb.querySelector(".subagent-ring") === window.firstRing'), true);
  assert.ok(await evaluate('document.querySelector(".subagent-dialog").textContent.includes("Found annual plan pricing.")'));
  assert.ok(await evaluate('document.querySelector(".subagent-dialog").textContent.includes("≈19.2k tokens")'));
  key('Escape'); await pause(80);
  assert.equal(await evaluate('document.querySelector(".subagent-dialog")'), null);
  assert.equal(await evaluate('document.activeElement === firstOrb'), true);
  assert.equal(await evaluate('document.querySelector(".subagent-peek").hidden'), true);
  checks.push('Live details/trace update without replacing orbs; Escape restores focus');
  await evaluate('document.querySelector("#finish").click()');
  await pause(1000);
  assert.equal(await evaluate('firstOrb.dataset.phase'), 'complete');
  assert.equal(await evaluate('firstRing.getAnimations({subtree:true}).filter(a => a.playState === "running").length'), 0);
  await evaluate('document.querySelector("#update").click()');
  assert.equal(await evaluate('firstRing.getAnimations({subtree:true}).filter(a => a.playState === "running").length'), 0);
  checks.push('Complete settles once and stays static on subsequent updates');
  await evaluate('document.querySelector("#tool").click()');
  assert.equal(await evaluate('getComputedStyle(firstRing, "::after").animationDuration'), '1.6s');
  checks.push('Tool use runs a faster ring highlight');
  const output = path.resolve(__dirname, '../release');
  fs.writeFileSync(path.join(output, 'subagent-orbs-desktop.png'), (await win.webContents.capturePage()).toPNG());
  await evaluate('document.querySelector("#theme").click()');
  fs.writeFileSync(path.join(output, 'subagent-orbs-dark.png'), (await win.webContents.capturePage()).toPNG());
  await evaluate('document.querySelector("#theme").click()');
  win.setContentSize(375, 812); await pause(180);
  assert.ok(await evaluate('document.documentElement.scrollWidth <= window.innerWidth'));
  await evaluate('document.querySelectorAll(".subagent-orb")[8].click()');
  await pause(180);
  const rect = await evaluate('(function(){var r=document.querySelector(".subagent-peek").getBoundingClientRect();return {left:r.left,right:r.right,top:r.top,bottom:r.bottom,width:innerWidth,height:innerHeight};})()');
  assert.ok(rect.left >= 0 && rect.right <= rect.width && rect.top >= 0 && rect.bottom <= rect.height);
  fs.writeFileSync(path.join(output, 'subagent-orbs-mobile-details.png'), (await win.webContents.capturePage()).toPNG());
  checks.push('375px layout and details stay inside viewport; light/dark rendering');
  await evaluate('document.querySelector("#replay").click()');
  assert.equal(await evaluate('document.querySelector("[data-phase=complete] .subagent-ring").getAnimations({subtree:true}).length'), 0);
  checks.push('Replayed completed states do not replay success animation');
  await win.webContents.debugger.attach('1.3');
  await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] });
  assert.equal(await evaluate('Array.from(document.querySelectorAll(".subagent-ring"), r => r.getAnimations({subtree:true}).length).reduce((a,b)=>a+b,0)'), 0);
  checks.push('Reduced-motion preference disables ring animation');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, checks, screenshots: ['subagent-orbs-desktop.png', 'subagent-orbs-dark.png', 'subagent-orbs-mobile-details.png'] }));
  win.destroy(); app.exit(0);
}).catch(error => { console.error(error); app.exit(1); });
setTimeout(() => { console.error('Subagent smoke check timed out'); app.exit(1); }, 45000).unref();
