import { mkdtempSync, rmSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { expect, it, vi } from 'vitest';
import { GituServer } from '../src/server/server.js';
import { ScriptedMockLlm } from '../src/llm/llm.js';
import { executeCoworkTool } from '../src/cowork/tools.js';
import type { CoworkAgent, CoworkStore } from '../src/cowork/store.js';
import type { CoworkMemory } from '../src/cowork/memory.js';
import type { CompanyStore } from '../src/company/store.js';
import type { ToolContext } from '../src/tools/tools.js';
import type { AsyncLocalStorage } from 'node:async_hooks';

it('creates companies, links existing agents, shares company memory and reuses scoped Cowork tools across restart', async () => {
  const root = mkdtempSync(path.join(os.tmpdir(), 'gitu-company-workspaces-'));
  vi.stubEnv('AGENT_GITU_HOME', root);
  const server = new GituServer({ passwordRequired: false, port: 0, llm: new ScriptedMockLlm([]) });
  const internal = server as unknown as {
    cowork(): CoworkStore; companies(): CompanyStore; coworkMemory(): CoworkMemory; coworkMemoryFor(agent: CoworkAgent): string;
    coworkToolContext(agent: CoworkAgent): ToolContext; coworkComputer(id: string): unknown;
    companyScope: AsyncLocalStorage<{ id: string; version: number }>;
  };
  let restarted: GituServer | undefined;
  try {
    const origin = 'http://localhost:' + await server.start(), roster = internal.cowork();
    const ari = roster.saveAgent({ name: 'Ari', systemPrompt: 'Coordinate requested work.', allowConfig: true, allowWrites: true });
    const milo = roster.saveAgent({ name: 'Milo', systemPrompt: 'Research customer evidence.' });
    const sana = roster.saveAgent({ name: 'Sana', systemPrompt: 'Help with operations.' });
    const conversation = roster.saveConversation({ kind: 'dm', memberIds: [ari.id] });
    const perms = { allowConfig: true, allowWrites: true, allowShell: false, chief: false, browser: false };
    const tool = (agent: CoworkAgent, conversationId: string, args: Record<string, unknown>) => executeCoworkTool(internal.coworkToolContext(agent), 'company_manage', args, perms, { agent, store: internal.cowork(), memory: internal.coworkMemory(), conversationId });
    const first = await tool(ari, conversation.id, { action: 'create', name: 'Research', purpose: 'Research customer evidence.', memberIds: [milo.id] });
    expect(first.ok, first.output).toBe(true);
    const second = await tool(ari, conversation.id, { action: 'create', name: 'Operations', purpose: 'Coordinate operational work.' });
    expect(second.ok, second.output).toBe(true);
    const alpha = internal.companies().get(first.companyLink!.id)!, beta = internal.companies().get(second.companyLink!.id)!;
    expect(alpha.leadId).toBe(ari.id); expect(beta.leadId).toBe(ari.id);
    const protectedProfile = await fetch(origin + '/api/cowork/agents/' + ari.id, { method: 'DELETE', headers: { origin } });
    expect(protectedProfile.status).toBe(409);
    expect(roster.listAgents()).toHaveLength(3);
    expect(roster.getAgent(ari.id)).toEqual(ari);
    const inCompany = <T>(id: string, work: () => T) => internal.companyScope.run({ id, version: 0 }, work);
    expect(inCompany(alpha.id, () => internal.cowork().listAgents().map(agent => agent.id))).toEqual([ari.id, milo.id]);
    const alphaAri = inCompany(alpha.id, () => internal.cowork().getAgent(ari.id)!);
    internal.companies().update(alpha.id, { monthlyBudgetUsd: null, maxFileBytes: null });
    internal.companies().transition(alpha.id, 'running');
    const added = await inCompany(alpha.id, () => tool(alphaAri, alpha.conversationId!, { action: 'add_agent', id: alpha.id, agentId: sana.id }));
    expect(added.ok, added.output).toBe(true);
    expect(roster.listAgents()).toHaveLength(3);
    expect(inCompany(alpha.id, () => internal.cowork().getConversation(alpha.conversationId!)?.kind)).toBe('group');
    expect(inCompany(beta.id, () => internal.cowork().getAgent(sana.id))).toBeUndefined();
    const contexts = [internal.coworkToolContext(ari), inCompany(alpha.id, () => internal.coworkToolContext(alphaAri)), inCompany(beta.id, () => internal.coworkToolContext(internal.cowork().getAgent(ari.id)!))];
    expect(new Set(contexts.map(context => context.cwd)).size).toBe(3);
    const computers = [internal.coworkComputer(ari.id), inCompany(alpha.id, () => internal.coworkComputer(ari.id)), inCompany(beta.id, () => internal.coworkComputer(ari.id))];
    expect(new Set(computers).size).toBe(3);
    const miloConversation = roster.saveConversation({ kind: 'dm', memberIds: [milo.id] });
    expect((await tool(milo, miloConversation.id, { action: 'remember', id: alpha.id, text: 'The pilot serves small teams in Nairobi.' })).ok).toBe(true);
    expect(internal.coworkMemoryFor(sana)).toContain('small teams in Nairobi');
    expect(internal.coworkMemoryFor(sana)).toContain('Research');
    internal.coworkMemory().remember(alphaAri, 'Ari private working preference.');
    expect(internal.coworkMemory().recall(ari)).toContain('Ari private working preference.');
    expect(internal.coworkMemoryFor(milo)).not.toContain('Ari private working preference.');
    expect((await tool(milo, miloConversation.id, { action: 'create', name: 'Unauthorized', purpose: 'Cannot create.' })).ok).toBe(false);
    const response = await fetch(origin + '/api/companies/' + alpha.id + '/members/' + milo.id, { method: 'DELETE', headers: { origin } });
    expect(response.status).toBe(200);
    expect(roster.getAgent(milo.id)).toEqual(milo);
    expect(inCompany(alpha.id, () => internal.cowork().getAgent(milo.id))).toBeUndefined();
    internal.companies().transition(alpha.id, 'paused');
    await server.stop();
    restarted = new GituServer({ passwordRequired: false, port: 0, llm: new ScriptedMockLlm([]) });
    const nextOrigin = 'http://localhost:' + await restarted.start();
    const next = await fetch(nextOrigin + '/api/cowork/agents').then(response => response.json()) as { agents: CoworkAgent[] };
    expect(next.agents).toHaveLength(3);
    expect(next.agents.every(agent => !agent.companyId)).toBe(true);
    const knowledge = await fetch(nextOrigin + '/api/companies/' + alpha.id + '/memory').then(response => response.json()) as { memories: { claim: string }[] };
    expect(knowledge.memories[0]?.claim).toContain('small teams in Nairobi');
  } finally {
    await restarted?.stop(); await server.stop(); vi.unstubAllEnvs();
    rmSync(root, { recursive: true, force: true });
  }
}, 60000);
